"""Запуск кабинета: `python -m cabinet`.

Точка входа в процесс. Отдельный модуль, а не `uvicorn cabinet.app:app`:
приложение собирается функцией `build_app`, и ей нужны зависимости. Импорт
`cabinet.app` не даёт готового `app` — специально, чтобы сборка оставалась
одной и явной, а не лежала на уровне модуля как побочный эффект импорта.

Зависимости здесь **боевые** и берутся из окружения: хранилище — `BotClient` к
внутреннему роутеру бота, отправитель писем — по конфигу почты. Умолчания
`build_app` (подставной бот и подставная почта) оставлены тестам и стенду
(`.claude/dev/cabinet_dev.py`) и в боевой запуск не попадают: иначе выложенный
кабинет вошёл бы любым адресом и показал подписки из фикстур (issue #45).

Без обязательных переменных окружения запуск **отвергается**, а не откатывается
на подставные: адрес бота и общий секрет задаются развёртыванием, а не
угадываются. Отказ — понятная строка в stderr и ненулевой код выхода, чтобы
юнит выкладки видел «сервис не поднялся», а не запускал демонстрацию.

Адрес прослушивания — `127.0.0.1`, а не `0.0.0.0`. Кабинет стоит за nginx
(CLAUDE.md, «Границы сервиса»): наружу его выставляет прокси, и слушать все
интерфейсы значило бы открыть внутренний сервис в обход него. Порт берётся из
`CABINET_PORT`, по умолчанию `8000`.
"""

from __future__ import annotations

import os
import sys
from collections.abc import Mapping

import uvicorn
from fastapi import FastAPI

from cabinet.app import build_app
from cabinet.bot_client import BOT_BASE_URL_ENV, BOT_SECRET_ENV, BotClient, BotConfigError
from cabinet.mail_sender import MailConfigError, MailSender

# Интерфейс и порт по умолчанию. Порт — настройка развёртывания, поэтому
# берётся из окружения; значение по умолчанию существует лишь чтобы
# `python -m cabinet` работал без конфигурации.
HOST = "127.0.0.1"
DEFAULT_PORT = 8000


def _required(source: Mapping[str, str], name: str, what: str) -> str:
    """Обязательная переменная окружения. Пустая — отказ, а не умолчание.

    Умолчание для адреса бота (`BotClient.DEFAULT_BASE_URL`) существует ради
    тестов и стенда, и боевой запуск его подхватить не должен: именно
    молчаливая подстановка и составляла дефект #45.

    В тексте отказа называется только **имя** переменной, но не её значение:
    секрет не печатается нигде — репозиторий публичный, а лог читают шире, чем
    задумано.
    """
    value = source.get(name, "").strip()
    if not value:
        raise BotConfigError(f"не задано {what}: переменная окружения {name}")
    return value


def build_from_env(env: Mapping[str, str] | None = None) -> FastAPI:
    """Собрать приложение боевыми зависимостями из окружения.

    Единственное место, где `build_app` получает **живые** зависимости, — и
    потому единственное, где видно, из чего выложенный кабинет собран:
    хранилище `BotClient` по `BOT_BASE_URL` и общему секрету, отправитель писем
    по конфигу почты. Подставные зависимости сюда не передаются ни одним путём.

    Параметр `env` — шов для теста, как у `MailSender.from_env`: без него
    читается настоящее окружение процесса.
    """
    source = os.environ if env is None else env
    store = BotClient(
        base_url=_required(source, BOT_BASE_URL_ENV, "адрес бота"),
        secret=_required(source, BOT_SECRET_ENV, "общий секрет"),
    )
    return build_app(store=store, mail_sender=MailSender.from_env(source))


def main() -> None:
    """Собрать приложение и запустить сервер.

    Порт читается здесь, а не в `build_app`: это параметр запуска процесса, а не
    зависимость приложения. Смешивать их значило бы тащить сокет в функцию,
    которую тест вызывает ради роутов.

    Ошибка конфигурации не глушится и не превращается в подстановку: она
    печатается и даёт ненулевой код выхода. Юнит выкладки видит отказ, а не
    работоспособный на вид кабинет на подставном боте.
    """
    port = int(os.environ.get("CABINET_PORT", DEFAULT_PORT))
    try:
        app = build_from_env()
    except (BotConfigError, MailConfigError) as exc:
        # `SystemExit` не печатает трассировку: оператор увидит одну понятную
        # строку, а не стек вызовов, из которого причину ещё надо вычитать.
        print(f"кабинет не запущен: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc
    uvicorn.run(app, host=HOST, port=port)


if __name__ == "__main__":
    main()
