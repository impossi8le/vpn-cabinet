"""Адрес привязки, отправленный на код, — чтобы шаг ввода кода не терялся.

Дефект: экран с полем кода был **одноразовым ответом** на отправку
(`POST /account/link/mail`). Человек уходил в почтовый ящик и возвращался на
`/account` обычным GET — а возвращаются из ящика именно так, — и поля не
оставалось, хотя код лежал в письме и действовал. Шаг, ради которого письмо и
просили, пропадал ровно в тот момент, когда человек готов его закончить.

Адрес живёт **на сервере, в памяти процесса**. Не в cookie и не в адресе
страницы: сюда человек возвращается GET-ом из ниоткуда, и адрес в URL осел бы
в истории браузера, а cookie — второй способ хранения рядом со способом
хранения кодов. Цена решения та же, что у хранилища кодов: перезапуск процесса
теряет память вместе с кодами, и это приемлемо — оба живут минуты.

Почему память не в `AuthMail`. Тот хранит коды **по адресу** и про аккаунт не
знает ничего: привязка ещё только предстоит, и адрес в коде — это «куда писали»,
а не «кому». Здесь же нужен ответ на другой вопрос: какому **аккаунту** показать
адрес, на который он просил код. Смешать это в `AuthMail` значило бы научить
хранилище кодов тому, чего оно не должно знать, — кто из аккаунтов какую почту
привязывает.

Почему у памяти **нет своего срока годности**. Адрес отдаётся экрану, только
пока код ещё действует (`AuthMail.has_pending`). Свой TTL завёл бы второй срок
рядом с первым, и однажды они разошлись бы: адрес погас, а код жив (или
наоборот), — и человек остался бы либо без шага при живом коде, либо с полем
для погасшего. Один срок, у кода, и этот модуль только спрашивает его.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from cabinet.auth_mail import AuthMail


@dataclass
class PendingMail:
    """Адрес незавершённой привязки почты по аккаунту.

    Один экземпляр — один процесс кабинета, как и `AuthMail`. Хранит словарь
    «аккаунт → адрес»: ключ — `account_id`, а не адрес, потому что адрес
    приходит с экрана, а аккаунт известен из сессии, и показать чужому
    аккаунту адрес, который вводил предыдущий, нельзя.
    """

    _addresses: dict[int, str] = field(default_factory=dict, init=False, repr=False)

    def remember(self, account_id: int, address: str) -> None:
        """Запомнить адрес, на который код только что ушёл.

        Доступна и при `RateLimited`: код из первого письма всё ещё действует,
        и шаг ввода обязан остаться, даже если повторную отправку отвергли.
        """
        self._addresses[account_id] = address

    def forget(self, account_id: int) -> None:
        """Забыть адрес: привязка завершена, шаг кода закончен."""
        self._addresses.pop(account_id, None)

    def live_address(self, account_id: int, auth_mail: AuthMail) -> str | None:
        """Адрес для экрана, только пока код действует; иначе `None`.

        Своего срока у записи нет: пользуемся кодом как единственным источником
        истины о том, идёт ли ещё шаг. Погасший код (истёк, использован,
        попытки исчерпаны) возвращает экран к форме адреса — поле для кода,
        которого уже нет, обещало бы шаг, которого нет.
        """
        address = self._addresses.get(account_id)
        if address is None:
            return None
        if not auth_mail.has_pending(address):
            return None
        return address
