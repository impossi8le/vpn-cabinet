class SessionStore(Protocol):
    """Хранилище сессий, как его видит кабинет.

    Адресуется **токеном**: владелец таблицы сессий — бот, и он опознаёт сессию
    по самому токену (`GET /internal/sessions/current` читает `Authorization:
    Bearer`). Хранилище в памяти хеширует его само (`sha256`), поэтому открытый
    токен за его пределы не выходит — приём тот же, что у кодов в `auth_mail`.

    Возвращается `Session`, а не `bool`: вызывающему нужны `account_id` и
    `expires_at` — иначе срок пришлось бы хранить второй копией, а без копии не
    показать, до когда человек вошёл.

    Обновление строки при заходе (`touch`) делает хранилище, а не вызывающий:
    владелец строки сессии — оно, и второй копии ни времени активности, ни срока
    быть не должно.
    """

    def create(
        self,
        *,
        account_id: int,
        token: str,
        expires_at: datetime,
        created_at: datetime,
    ) -> Session:
        """Записать сессию и вернуть строку, какой она легла в хранилище.

        `created_at` — момент появления сессии, и он **не** сдвигается
        продлением: от него считается абсолютный горизонт (`MAX_SESSION_LIFETIME`).
        Если хранилище его не сохранит, у продления не останется потолка, и
        токен, которым пользуются хотя бы раз в TTL, будет жить вечно (#53).

        `token` — им адресуется строка. `Session.token` в ответе может быть
        другим: у бота токен генерирует он сам, и кабинет принимает его.
        """
        ...

    def find(self, token: str) -> Session | None:
        """Найти сессию по токену. `None` — не найдена."""
        ...

    def touch(self, token: str, *, moment: datetime, expires_at: datetime) -> None:
        """Отметить активность **и** сдвинуть срок. Отсутствие сессии — не ошибка.

        Срок продлевается тем же заходом, что и активность: кабинет открывают
        редко, и «зашёл — значит, вход ещё нужен» обязано отражаться на
        `expires_at`, а не только на справочном `last_seen_at` (`Session`).

        Обновляется **только существующая** строка. Пропавшей сессии не заводим:
        отозванной или истёкшей записи здесь уже нет, и «обновление» не должно
        её воскрешать — иначе выход обходился бы обычным запросом.
        """
        ...

    def revoke(self, token: str) -> None:
        """Отозвать сессию. Повторный отзыв — не ошибка (§4: выход идемпотентен)."""
        ...


@dataclass(frozen=True)
class Session:
    """Строка сессии, какой её отдаёт хранилище.

    `account_id` — владелец. `chat_id` здесь нет намеренно: способ входа в
    сессии не участвует, и место ему — в аккаунте.

    `last_seen_at` — справочное время последнего захода. `expires_at` сдвигается
    тем же заходом, но **не** от `last_seen_at`: продлевает живой срок
    `SessionService.resolve`, считая его от текущего момента. Разница важная —
    `last_seen_at` остаётся фактом «когда заходили», а срок отвечает на вопрос
    «до когда вход ещё действует», и это разные вещи. Забытая сессия (человек не
    заходил дольше TTL) не продлевается и истекает сама.

    `created_at` — когда сессия появилась. Продлением он не сдвигается, и от
    него считается абсолютный горизонт: без него продление уводило бы срок
    вперёд без конца, и «угнанный токен перестаёт работать сам» оставалось бы
    верным только для токена, которым не пользуются (#53).

    `created_at` бывает `None` у живого хранилища: `GET /internal/sessions/current`
    его не отдаёт, и придумывать момент появления сессии кабинет не вправе. Это
    не потеря горизонта, а его передача: срок живых сессий ведёт бот, а
    `SessionService` в этом случае горизонта не сужает.
    """

    token: str
    account_id: int
    expires_at: datetime
    created_at: datetime | None = None
    last_seen_at: datetime | None = None


@dataclass(frozen=True)
class SessionView:
    """Сессия, какой её видит вызывающий код после выдачи или проверки.

    Токен здесь есть: он показывается **один раз**, в момент выдачи, и держать
    его копию в хранилище незачем — оттуда он не вернётся никогда. Вызывающий
    сам решает, куда его положить (cookie `HttpOnly`), но видеозапись сессии без
    токена неполна, поэтому он входит в результат.
    """

    account_id: int
    token: str
    expires_at: datetime


def hash_token(token: str) -> str:
    """Хеш токена для хранилища.

    Хранится вместо токена: репозиторий публичный, и токен, попавший в дамп или
    лог, — это уже угнанная сессия. По хешу токен не восстанавливается, а
    сравнение с ним ничего о токене не сообщает.
    """
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def new_token(nbytes: int = MIN_TOKEN_BYTES) -> str:
    """Случайный токен. Источник — `secrets`, не `random`: `random` предсказуем
    по начальному состоянию, а предсказуемость токена означает чужой вход.

    Минимум энтропии проверяется, а не подразумевается: уступка в один аргумент
    ослабила бы все сессии разом, и заметить это надо здесь, а не в бою.
    """
    if nbytes < MIN_TOKEN_BYTES:
        raise ValueError(f"токен короче {MIN_TOKEN_BYTES} байт: энтропии не хватает")
    return secrets.token_urlsafe(nbytes)


class SessionService:
    """Выдача, проверка и отзыв сессий кабинета.

    Часы подаются снаружи: тест на истечение обязан быть детерминированным, а не
    зависеть от того, как быстро отработал прогон. В бою часы —
    `datetime.now(UTC)`.

    Фабрика токена — тоже шов, и по той же причине: коллизия источника токенов
    (дважды выданный один токен) должна проверяться детерминированно, а не
    ожиданием вероятностного события.
    """

    def __init__(
        self,
        *,
        store: SessionStore,
        accounts: AccountStore,
        ttl: timedelta = DEFAULT_SESSION_TTL,
        max_lifetime: timedelta = MAX_SESSION_LIFETIME,
        now: Callable[[], datetime] = lambda: datetime.now(UTC),
        token_factory: Callable[[], str] = new_token,
    ) -> None:
        self._store = store
        self._accounts = accounts
        self._ttl = ttl
        self._max_lifetime = max_lifetime
        self._now = now
        self._new_token = token_factory

    @property
    def ttl(self) -> timedelta:
        """Срок сессии, выданной **в память** (`SingleSessionStore`).

        Для живой сессии у бота срок другой, и cookie берёт **его**, а не этот:
        см. `max_age`. Здесь не «срок вообще», а срок того хранилища, которое
        сроком владеет, — сегодня это память.
        """
        return self._ttl

    def max_age(self, view: SessionView) -> timedelta:
        """Сколько живёт cookie **этой** сессии.

        Не «полный TTL», а сколько осталось до её срока: у живого хранилища бот
        отдаёт свой срок (сейчас 30 дней без продления), и cookie на 180 дней
        обещала бы браузеру вход, которого сервер уже не даст, — а браузер
        посылал бы мёртвый токен ещё 150 дней. Срок читается из `expires_at`,
        который вернул `sign_in`/`resolve`, поэтому cookie и запись говорят одно.

        У хранилища в памяти `expires_at` — это `now + ttl`, поэтому здесь
        получается прежний TTL.
        """
        remaining = _as_utc(view.expires_at) - _as_utc(self._now())
        return remaining if remaining > timedelta(0) else timedelta(0)

    # ---------- выдача ----------

    def sign_in(self, account_id: int) -> SessionView:
        """Выдать сессию аккаунту. Способ входа значения не имеет.

        Главное свойство метода: сессия выдаётся **по аккаунту**, поэтому
        аккаунт, заведённый по почте (`chat_id = NULL`), получает её ровно так
        же, как аккаунт из Telegram. Различия способов входа здесь нет вовсе —
        иначе оно вернулось бы в сессии, откуда мы его убрали.

        Аккаунт читается перед выдачей намеренно: сессия на несуществующий
        аккаунт была бы ссылкой в пустоту, и «аккаунта нет» — это отказ входа,
        а не сбой хранилища.
        """
        if self._accounts.find_by_id(account_id) is None:
            raise NoAccount(f"аккаунт {account_id} не найден")

        token = self._new_token()
        moment = _as_utc(self._now())
        session = self._store.create(
            account_id=account_id,
            token=token,
            expires_at=moment + self._ttl,
            created_at=moment,
        )
        return SessionView(
            account_id=session.account_id,
            # Токен берётся из записи, а не из локальной переменной: у бота его
            # генерирует он сам, и cookie обязан нести именно его — иначе
            # выданная сессия не найдётся на следующем заходе.
            token=session.token,
            expires_at=session.expires_at,
        )

    # ---------- проверка ----------

    def resolve(self, token: str | None) -> SessionView | None:
        """Разобрать токен в сессию или вернуть `None`.

        `None` — не отказ: экран входа на это отвечает формой. Токен приходит из
        cookie браузера, и «cookie нет» — обычное состояние первого захода, а не
        сбой, ради которого стоило бы бросать исключение.

        Срок проверяется здесь, а не в хранилище: хранилище отвечает «что
        записано», а «не истекло ли» зависит от часов, которые подаёт
        вызывающий, и считаться должно в одном месте со сроком выдачи.

        Истёкшую сессию гасим сразу: держать её дальше смысла нет, а оставленная
        запись — это ещё действующий токен в таблице.

        Живая сессия **продлевается** здесь же: срок сдвигается на полный TTL от
        текущего момента, потому что кабинет открывают редко и зашедший человек
        вход сохраняет, а не теряет его на исходе срока. Продление — только у
        живой сессии: истёкшая выше уже погашена и сюда не доходит, а отозванной
        в хранилище нет вовсе (`find` вернул `None`), поэтому продление не
        воскрешает ни то, ни другое. Забытая сессия (человек не заходил дольше
        TTL) продления не получает и истекает сама.

        Продление не безусловно: срок не уходит дальше горизонта
        (`MAX_SESSION_LIFETIME`), отсчитанного от создания сессии. Без потолка
        токен, которым пользуются хотя бы раз в TTL, жил бы вечно — и тогда
        «угнанный токен перестаёт работать сам» было бы верно только для
        токена, которым не пользуются (#53).

        Активность отмечается **после** проверки срока: запрос с истёкшим токеном
        активностью не является.
        """
        if not token:
            return None

        session = self._store.find(token)
        if session is None:
            return None

        moment = _as_utc(self._now())
        if _as_utc(session.expires_at) <= moment:
            self._store.revoke(token)
            return None

        # Откуда берётся срок. У хранилища в памяти (`created_at` есть) он
        # скользит: полный TTL от текущего момента, с потолком от создания
        # сессии. У живого хранилища (`created_at` нет) срок — тот, что записан
        # в сессии: его ведёт бот, и кабинет не обещает больше, чем она живёт.
        # Считать здесь `moment + ttl` значило бы поставить cookie на 180 дней
        # поверх тридцатидневной записи и разлогинить активного человека на 30-й.
        if session.created_at is None:
            expires_at = _as_utc(session.expires_at)
        else:
            expires_at = min(moment + self._ttl, _as_utc(session.created_at) + self._max_lifetime)
        self._store.touch(token, moment=moment, expires_at=expires_at)
        return SessionView(
            account_id=session.account_id,
            token=token,
            expires_at=expires_at,
        )

    # ---------- выход ----------

    def sign_out(self, token: str | None) -> None:
        """Выход. Идемпотентно: повторный выход — не ошибка (§4).

        Идемпотентность здесь не вежливость, а требование: выход — та дверь,
        которой человек закрывает себе доступ, и отказ «сессии уже нет» оставил
        бы его с ощущением, что выход не сработал, — при том что токен уже
        недействителен.
        """
        if not token:
            return
        self._store.revoke(token)


def _as_utc(value: datetime) -> datetime:
    """Привести время к UTC.

    Хранилище может отдать срок без зоны (бот пишет `DATETIME`), а часы приходят
    с зоной — сравнить такие `datetime` напрямую Python не даст, бросит
    `TypeError` в середине обработки запроса. Наивное время договорились считать
    UTC: так его пишет сервис. Тот же приём, что в `subscriptions`.
    """
    if value.tzinfo is None:
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


@dataclass(frozen=True)
class _StoredSession:
    """Запись сессии в памяти — **без** открытого токена.

    Ключ словаря и так хеш, но хранить рядом ещё и токен значило бы держать его
    в памяти вне момента выдачи: `repr(Session)` вывел бы его в лог или в дамп.
    Поэтому запись несёт `token_hash`, а токен подставляется при возврате из
    `find`/`create` (см. `_session_with_token`).
    """

    token_hash: str
    account_id: int
    expires_at: datetime
    created_at: datetime
    last_seen_at: datetime | None = None


def _session_with_token(stored: _StoredSession, token: str) -> Session:
    """Собрать `Session` из записи, подставив токен вызывающего.

    Токен приходит аргументом и в записи не хранится — так он не оседает в
    памяти хранилища, а возвращается только тому, кто его и предъявил.
    """
    return Session(
        token=token,
        account_id=stored.account_id,
        expires_at=stored.expires_at,
        created_at=stored.created_at,
        last_seen_at=stored.last_seen_at,
    )


@dataclass
class SingleSessionStore:
    """Сессии в памяти процесса: тот же `SessionStore`, без базы и без сети.

    Остаётся тестам и стенду. В бою сессии живут у бота (`cabinet.bot_client.
    BotSessionStore`), и этот класс — умолчание `build_app`, то есть режим
    «память процесса». Форма — общий протокол, поэтому подмена на живой бот не
    требует правок вызывающего кода, а поведение сессий проверяется здесь, не
    поднимая ради этого второе хранилище.

    Ключ словаря — **хеш** токена (`hash_token`), а в записи (`_StoredSession`)
    открытого токена нет вовсе: репозиторий публичный, и токен, попавший в дамп
    памяти или в `repr`, — это уже угнанная сессия. Токен подставляется только в
    ответ `find`/`create`, то есть тому, кто его и предъявил.

    Состояние сбрасывается при перезапуске процесса: памяти процесса после
    перезапуска нет, и вход, живущий только в ней, теряется — ровно та причина,
    по которой в бою подставляется бот.
    """

    sessions: dict[str, _StoredSession] = field(default_factory=dict)

    def create(
        self,
        *,
        account_id: int,
        token: str,
        expires_at: datetime,
        created_at: datetime,
    ) -> Session:
        """Записать сессию.

        Повтор по тому же хешу — не «новая сессия», а коллизия источника токенов:
        токен, выданный дважды, означал бы, что второй человек получает доступ
        первого. Отказ, а не тихая перезапись — иначе сессию первого сменила бы
        сессия второго, и заметить это было бы негде.

        `created_at` хранится рядом с `expires_at` и продлением не меняется:
        это точка отсчёта абсолютного горизонта, и потерять её значит вернуть
        бесконечное продление (#53).
        """
        token_hash = hash_token(token)
        if token_hash in self.sessions:
            raise SessionRefused("хеш токена уже занят: источник токенов выдал повтор")
        stored = _StoredSession(
            token_hash=token_hash,
            account_id=account_id,
            expires_at=expires_at,
            created_at=created_at,
        )
        self.sessions[token_hash] = stored
        return _session_with_token(stored, token)

    def find(self, token: str) -> Session | None:
        """Сессия или `None`. Поиск идёт по хешу, поэтому содержимое токена на
        время ответа не влияет."""
        stored = self.sessions.get(hash_token(token))
        if stored is None:
            return None
        return _session_with_token(stored, token)

    def touch(self, token: str, *, moment: datetime, expires_at: datetime) -> None:
        """Отметить активность и продлить срок — одним движением.

        Пишется **только существующая** строка (`if session is not None`):
        отозванной или истёкшей здесь уже нет, и продление не должно заводить её
        заново. Иначе «обновление» воскрешало бы вышедшего человека по обычному
        запросу, и выход переставал бы что-либо значить.
        """
        token_hash = hash_token(token)
        stored = self.sessions.get(token_hash)
        if stored is not None:
            self.sessions[token_hash] = replace(stored, last_seen_at=moment, expires_at=expires_at)

    def revoke(self, token: str) -> None:
        """Отозвать. Отсутствие сессии — не ошибка: выход идемпотентен."""
        self.sessions.pop(hash_token(token), None)
