"""Сценарии входа и регистрации (W2.3, W2.4, W3.1).

Три двери в кабинет, и все три ведут к одному `account_id`:

- **Регистрация по почте** — адрес, код на почту, аккаунт с `chat_id = NULL`.
- **Вход по почте** — тот же адрес и код, но второй аккаунт не заводится.
- **Вход по Telegram** — подтверждённый ботом `chat_id`; аккаунт находится или
  заводится (§5 контракта, шаг уже сделан ботом в `/auth/poll`).

Почему это один модуль, а не три. Двери различаются тем, **что на входе**, и
совпадают тем, что на выходе. Совпадение здесь и есть то, что проверяется тестом
на ключевое свойство: сессия, полученная любым способом, ведёт к одному и тому же
`account_id`. Разложи мы сценарии по файлам — это свойство проверялось бы на
стыке трёх модулей, то есть нигде.

Почему почта и Telegram не перезаписывают друг друга. Это §3.3 спеки, и оно
закрыто не здесь, а в `linking.py`: привязка — только на `NULL`, и `chat_id`
приходит лишь подтверждённым ботом. Вход сюда ничего не добавляет, он вызывает
`Linking`, а не повторяет его проверки. Иначе проверка порядка разъехалась бы с
оригиналом — и «привязка никогда не проще входа» перестало бы быть правдой именно
там, где это опаснее всего.

Границы. Ни сети, ни базы: хранилище и сессии подставляются, а в бою за ними
стоит живой бот. Почтовый код уже проверен `AuthMail` до того, как адрес попал
сюда.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from cabinet.accounts import Account
from cabinet.auth_mail import AuthMail, AuthMailError
from cabinet.linking import Linking, LinkResult
from cabinet.mail_sender import MailError
from cabinet.sessions import (
    SessionRefused,
    SessionService,
    SessionView,
)

__all__ = [
    "AccountRegistrar",
    "AccountStore",
    "MailSignInError",
    "SignInError",
    "SignInResult",
    "SignInService",
]


class SignInError(Exception):
    """Вход не состоялся. Сообщение — для оператора и лога, не для экрана.

    Экрану тексты этого исключения показывать нельзя: разный ответ на «почта
    занята» и «почты нет» выдал бы, кто где зарегистрирован. Наружу из кабинета
    уходит одно сообщение, подробность остаётся здесь — тот же приём, что в
    `linking.LinkRefused`.
    """


class MailSignInError(SignInError):
    """Код не принят: не запрашивался, истёк, не совпал или попытки исчерпаны.

    Отделено от прочих отказов: у экрана это одно состояние («введите код
    заново»), но от «хранилище сломалось» его надо отличать — иначе сбой
    хранилища показывался бы как неверный код человека.
    """

    def __init__(self, message: str, *, attempts_left: int | None = None) -> None:
        super().__init__(message)
        # `attempts_left` — подсказка «осталось N попыток», когда `AuthMail` её
        # знает. Необязательна: у «кода не было» и «срок истёк» попыток не
        # остаётся, и выдумывать ноль нельзя — экран показал бы «0 из 5» на
        # состояние, где счёт неприменим.
        self.attempts_left = attempts_left


class AccountStore(Protocol):
    """Хранилище аккаунтов, как его видит вход.

    Шире, чем протокол связывания (`linking.AccountStore`), и это не
    расхождение: входу нужны методы поиска **и** `create_account` — без него
    сценарий регистрации не собрать. Мок даёт эту форму целиком; живой клиент —
    через адаптер (`cabinet.bot_client.BotStore`), у которого `find_by_mail`,
    `find_by_chat_id` и `create_account` появились вместе со связыванием
    (issue #47). `create_account` там идёт на `POST /internal/accounts` с
    `mail_verified_at` — без адаптера вход по почте отвечал бы 500.

    Почта без `mail_verified_at` не создаётся — инвариант 2. Проверяет это
    хранилище, а не вызывающий код: проверка должна стоять там, где запись,
    иначе третья дверь однажды её забудет.
    """

    def find_by_id(self, account_id: int) -> Account | None:
        """Прочитать аккаунт по `id`."""
        ...

    def find_by_mail(self, mail: str) -> Account | None:
        """Найти аккаунт по почте. `None` — не найден, а не ошибка."""
        ...

    def find_by_chat_id(self, chat_id: int) -> Account | None:
        """Найти аккаунт по Telegram id. Симметрично поиску по почте."""
        ...

    def create_account(
        self,
        *,
        chat_id: int | None = None,
        mail: str | None = None,
        mail_verified_at: datetime | None = None,
    ) -> Account:
        """Завести аккаунт. Занятый `chat_id`/`mail` — коллизия хранилища, а не
        тихая перезапись."""
        ...


@dataclass(frozen=True)
class SignInResult:
    """Чем кончился вход.

    `session` — выданная сессия: одно состояние входа на все три двери, и это
    главное в этом результате. `account` — аккаунт, к которому она ведёт;
    `created` — завели ли его этим входом.

    `created` нужен инварианту «привязывать `chat_id` можно только пока аккаунт
    новый» (§3.3): экран по нему решает, предлагать ли привязку Telegram. Флаг
    стоит здесь, а не считается вызывающим по времени, потому что признак уже
    известен в точке, где принимается решение «нашли или завели», — и второй
    способ его получить разошёлся бы с первым.
    """

    account: Account
    session: SessionView
    created: bool

    @property
    def account_id(self) -> int:
        """Идентификатор аккаунта. Тот же для любой двери — по нему и
        проверяется «одно состояние входа»."""
        return self.session.account_id


class AccountRegistrar:
    """Заводит аккаунт по подтверждённому адресу.

    Отдельный класс, потому что это единственное место, где почта становится
    аккаунтом, — и единственное, где нужно помнить про инвариант 2. Хранилище
    проверяет его повторно, но забыть `mail_verified_at` здесь нельзя даже
    случайно: подставляется момент, полученный от `AuthMail`, а не «сейчас» из
    вызывающего кода. Момент берётся у тех же часов, что проверяли код, — иначе
    отметка подтверждения разошлась бы с моментом проверки.
    """

    def __init__(self, store: AccountStore, auth_mail: AuthMail) -> None:
        self._store = store
        self._auth_mail = auth_mail

    def register_by_mail(self, mail: str) -> Account:
        """Завести аккаунт по адресу, владение которым уже доказано.

        Вызывается **после** `AuthMail.verify`: сюда адрес приходит с
        подтверждением, а не из формы.
        """
        return self._store.create_account(mail=mail, mail_verified_at=self._auth_mail.now())


class SignInService:
    """Три двери в кабинет: почта-регистрация, почта-вход, Telegram.

    Сервис **складывает** готовые части: `AuthMail` проверяет код, `SignInService`
    решает по его результату, что делать с аккаунтом, `SessionService` выдаёт
    сессию. Ни одна проверка здесь не повторяет чужую — иначе их стало бы две, и
    они разошлись бы.

    Порядок в каждой двери — это и есть защита, поэтому он зафиксирован по шагам:

    1. **Сначала подтверждение, потом создание.** Аккаунт по почте заводится
       только после `AuthMail.verify`: иначе заявленный в браузере адрес создавал
       бы запись, и pre-account hijacking (§3.3) открылся бы на шаге, где раньше
       его не было.
    2. **Сначала поиск, потом создание.** Повторный вход по тому же адресу не
       заводит второй аккаунт — иначе у человека с одной почтой их становилось бы
       столько, сколько раз он зашёл.
    3. **Сессия — по аккаунту, последней.** К этому моменту аккаунт существует,
       и его `id` одинаков независимо от двери; сессия не знает, откуда он взялся.
    """

    def __init__(
        self,
        *,
        store: AccountStore,
        auth_mail: AuthMail,
        sessions: SessionService,
        linking: Linking | None = None,
    ) -> None:
        self._store = store
        self._auth_mail = auth_mail
        self._sessions = sessions
        self._linking = linking
        self._registrar = AccountRegistrar(store, auth_mail)

    # ---------- почта: регистрация и вход — одна дверь ----------

    def request_mail_code(self, mail: str) -> None:
        """Запросить код на адрес.

        Обёртка нужна ради перевода отказов: `AuthMail` бросает свои типы,
        `mail_sender` — `MailError` при сбое транспорта, а экран кабинета
        ветвится по нашим.

        `RateLimited` **не** переводится в `MailSignInError` и проходит как есть:
        у него есть `retry_after_seconds`, который экран показывает («попробуйте
        через минуту»), и свести его к общему отказу значило бы потерять именно
        эту подсказку. Сбой транспорта, наоборот, переводится: «письмо не ушло» —
        это отказ операции, а не состояние человека.
        """
        try:
            self._auth_mail.request_code(_normalize_mail(mail))
        except MailError as exc:
            raise SignInError("письмо с кодом не отправлено") from exc

    def sign_in_with_mail(self, mail: str, code: str) -> SignInResult:
        """Войти по почте, заведя аккаунт, если его ещё нет.

        Регистрация и вход здесь — **одно действие с разным исходом**, и это не
        упрощение, а следствие §3.3: кабинет различает их только для того, чтобы
        решить, предлагать ли привязку Telegram. Аккаунт в обоих случаях
        появляется одинаковый (`mail` + `mail_verified_at`, `chat_id = NULL`), и
        второй аккаунт на тот же адрес не заводится никогда.

        Порядок проверок:

        1. код — до всего остального: без доказанного владения адресом ни поиск,
           ни создание смысла не имеют, а неудачная попытка не должна оставлять
           после себя изменённое состояние;
        2. поиск существующего аккаунта — вход;
        3. создание — регистрация;
        4. сессия.

        Код проверяется **до** поиска аккаунта намеренно: иначе по разнице
        ответов («аккаунта нет» приходит быстрее, чем «код не тот») можно было бы
        перебором адресов выяснять, кто зарегистрирован.
        """
        address = _normalize_mail(mail)

        self._verify_mail(address, code)

        existing = self._store.find_by_mail(address)
        if existing is not None:
            return self._session_for(existing, created=False)

        account = self._registrar.register_by_mail(address)
        return self._session_for(account, created=True)

    # ---------- Telegram ----------

    def sign_in_with_telegram(self, chat_id: int, *, account_id: int | None = None) -> SignInResult:
        """Войти по подтверждённому боту `chat_id`.

        Флоу бота (`/auth/link` + `/auth/poll`, §5 контракта) **переиспользуется
        как есть**: сюда `chat_id` приходит уже подтверждённым человеком в
        Telegram, и кабинет его не выдумывает и никому на слово не верит.

        Порядок:

        1. если бот вернул `account_id` рядом с токеном (§5), доверяем ему: он
           уже нашёл или завёл аккаунт для этого `chat_id`. Это обычный путь —
           решение «нашли или завели» принято там, где есть подтверждение;
        2. иначе ищем аккаунт по `chat_id` сами;
        3. не нашли — заводим. При подтверждённом `chat_id` это безопасно:
           подтверждение уже произошло, и `chat_id` доказан человеком.

        Сессия — по `account_id` из любого шага, поэтому аккаунт, заведённый по
        Telegram, попадёт в тот же `account_id`, что и после привязки почты:
        способ входа не участвует в том, чья это сессия.
        """
        if account_id is not None:
            account = self._require_account(account_id)
            return self._session_for(account, created=False)

        existing = self._store.find_by_chat_id(chat_id)
        if existing is not None:
            return self._session_for(existing, created=False)

        account = self._store.create_account(chat_id=chat_id)
        return self._session_for(account, created=True)

    # ---------- привязка почты к вошедшему аккаунту ----------

    def link_mail(self, account_id: int, mail: str, code: str) -> LinkResult:
        """Привязать почту к аккаунту, уже вошедшему по Telegram.

        Живёт здесь, а не на экране, потому что это тот же сценарий с кодом: код
        проверяется `AuthMail` (внутри `Linking.link_mail`), привязка — только на
        пустое место (§3.3). Модуль ничего не добавляет к связыванию: он его
        вызывает. Так «привязка не проще входа» остаётся правдой в одном месте —
        `linking.py`, — а не в двух.

        Отказы кода (`AuthMailError` из `verify`) переводятся в `MailSignInError`
        тем же помощником, что у входа: HTTP-слой ловит наш тип, и истёкший или
        несовпавший код без перевода долетел бы до него чужим исключением — то
        есть 500 на ошибку человека вместо отказа на экране. Второй раз код не
        проверяется: его уже проверил `Linking.link_mail`, а код одноразовый —
        повторная проверка не нашла бы записи и отвергла бы верный код.

        `Linking` необязателен: без него связывание не подключено, и вызов —
        это ошибка развёртывания, а не состояние сценария.
        """
        if self._linking is None:
            raise SignInError("связывание способов входа не подключено")
        try:
            return self._linking.link_mail(account_id, mail=mail, code=code)
        except AuthMailError as exc:
            raise _code_refusal(exc) from exc

    # ---------- служебное ----------

    def _verify_mail(self, mail: str, code: str) -> None:
        """Проверить код, переведя отказы `AuthMail` в наш отказ входа.

        Типы `AuthMail` не текут наружу: вызывающий код кабинета не должен
        зависеть от того, что под ним. Неверный код, истёкший и «не
        запрашивался» сводятся к `MailSignInError`, потому что для экрана это
        одно действие человека — ввести код заново.
        """
        try:
            self._auth_mail.verify(mail, code)
        except AuthMailError as exc:
            raise _code_refusal(exc) from exc

    def _session_for(self, account: Account, *, created: bool) -> SignInResult:
        """Выдать сессию аккаунту. Одна точка выдачи на все три двери.

        Одна — намеренно: если бы каждая дверь звала `SessionService.sign_in`
        сама, различие между дверями могло бы вернуться сюда исподволь (одна
        дверь передала бы `chat_id`, другая — почту), и «одно состояние входа»
        перестало бы держаться. Здесь на входе только `account.id`, и это видно
        по сигнатуре.

        Отказ сессии переводится в наш (`SignInError`): по тому же правилу, что
        и у `AuthMail`, — вызывающий код кабинета ловит один тип входа, а не
        типы всех слоёв под ним. `account.id` может быть `None` только у
        аккаунта, ещё не записанного хранилищем, — а сюда такие не попадают:
        аккаунт берётся из хранилища или создаётся там до вызова.
        """
        if account.id is None:
            raise SignInError("аккаунт без id: хранилище не записало его")
        try:
            session = self._sessions.sign_in(account.id)
        except SessionRefused as exc:
            raise SignInError("сессия не выдана") from exc
        return SignInResult(account=account, session=session, created=created)

    def _require_account(self, account_id: int) -> Account:
        """Прочитать аккаунт по `id` или отказать.

        «Нет аккаунта» — не исключение хранилища, а расхождение состояния:
        вызывающий назвал `account_id`, которого нет. Отказ наш (`SignInError`),
        а не из `cabinet.sessions`: наружу из входа не должен течь тип слоя,
        который под ним.
        """
        account = self._store.find_by_id(account_id)
        if account is None:
            raise SignInError(f"аккаунт {account_id} не найден")
        return account


def _code_refusal(exc: AuthMailError) -> MailSignInError:
    """Перевести отказ `AuthMail` в наш отказ кода.

    Помощник общий для двух путей — входа и привязки почты. Обе двери проверяют
    **тот же** код тем же `AuthMail`, и перевод отказа обязан совпадать: разойдись
    он, и на одной двери «осталось N попыток» потерялось бы, а на другой нет.
    Здесь формула перевода в одном месте, а не скопирована по вызовам.

    `attempts_left` переносится, только когда `AuthMail` его знает: у «кода не
    запрашивали» и «срок истёк» попыток не остаётся, и нулём их не подменяем —
    экран показал бы «осталось 0» на состояние, где счёт неприменим.
    """
    return MailSignInError("код не принят", attempts_left=getattr(exc, "attempts_left", None))


def _normalize_mail(mail: str) -> str:
    """Привести адрес к сопоставимому виду: без пробелов по краям, строчными.

    Тот же вид, что у `auth_mail._normalize`, и это не дублирование ради
    аккуратности, а условие правильности: код подтверждения хранится по
    нормализованному адресу, и заведи мы аккаунт на исходную строку с большой
    буквой — при следующем входе `verify` принял бы код, а `find_by_mail` не
    нашёл бы аккаунт на этот же адрес. Второй аккаунт на один ящик, и подписки
    разъехались бы.

    Контракт (§1) требует того же от поиска: `User@Example.COM` и
    `user@example.com` — один аккаунт.
    """
    return mail.strip().lower()
